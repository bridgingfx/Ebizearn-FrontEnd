/** Normalize free text ("Instagram", "ig", "tiktok") to a brand key. */
export function platformKey(raw?: string | null): string | null {
  const v = (raw ?? '').trim().toLowerCase();
  if (!v) return null;
  if (/(insta|ig\b)/.test(v)) return 'instagram';
  if (/tik/.test(v)) return 'tiktok';
  if(/(youtube|yt\b)/.test(v)) return 'youtube';
  if (/^(x|twitter)$/.test(v)) return 'x';
  if (/face/.test(v)) return 'facebook';
  if (/whatsapp|wa\b/.test(v)) return 'whatsapp';
  if (/telegram|tg\b/.test(v)) return 'telegram';
  if (/linked/.test(v)) return 'linkedin';
  return null;
}

