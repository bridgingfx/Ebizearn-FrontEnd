const byCode = new Map(COUNTRIES.map((c) => [c.code, c.name]));

/** Full country name from an ISO code. Falls back to the code itself. */
export function countryName(code?: string | null): string {
  if (!code) return 'Unknown';
  return byCode.get(code.toUpperCase()) || code.toUpperCase();
}

/** Flag emoji from an ISO country code. */
export function countryFlag(code?: string | null): string {
  if (!code || code.length !== 2) return '🌍';
  const upper = code.toUpperCase();
  const offset = 0x1f1e6 - 65; // Regional indicator A
  return String.fromCodePoint(...[...upper].map((c) => c.charCodeAt(0) + offset));
}
